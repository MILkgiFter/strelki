// Формы полей: силуэт, внутри которого живут змейки. Без DOM.
//
// Фигура = { id, name, aspect, fn } или { id, name, art }:
//  fn(u, v) → true, если точка внутри; u, v ∈ [-1, 1], v растёт вниз; aspect = ширина / высота;
//  art — ASCII-рисунок ('#' — внутри, всё остальное — снаружи), пиксели квадратные,
//        масштабируется до сетки ближайшим соседом.

// ---------- помощники ----------
function inPoly(u, v, pts) {
  let inside = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, yi] = pts[i];
    const [xj, yj] = pts[j];
    if (yi > v !== yj > v && u < ((xj - xi) * (v - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
const regular = (n, r, rot = -Math.PI / 2) =>
  Array.from({ length: n }, (_, i) => [Math.cos(rot + (i * 2 * Math.PI) / n) * r, Math.sin(rot + (i * 2 * Math.PI) / n) * r]);
const starPts = (n, r1, r2) =>
  Array.from({ length: n * 2 }, (_, i) => {
    const a = -Math.PI / 2 + (i * Math.PI) / n;
    const r = i % 2 ? r2 : r1;
    return [Math.cos(a) * r, Math.sin(a) * r];
  });
const inCircle = (u, v, cx, cy, r) => (u - cx) ** 2 + (v - cy) ** 2 <= r * r;
const band = (y, a, b) => y >= a && y <= b;

