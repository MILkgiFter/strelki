// ---------- маска ----------
export const shapeAspect = (s) => (s.art ? s.art[0].length / s.art.length : s.aspect);

// 1 — клетка внутри фигуры
export function shapeMask(s, cols, rows) {
  const m = new Uint8Array(cols * rows);
  for (let y = 0; y < rows; y++) {
    for (let x = 0; x < cols; x++) {
      let inside;
      if (s.art) {
        const row = s.art[Math.min(s.art.length - 1, Math.floor(((y + 0.5) * s.art.length) / rows))];
        inside = row[Math.min(row.length - 1, Math.floor(((x + 0.5) * row.length) / cols))] === '#';
      } else {
        inside = s.fn(((x + 0.5) / cols) * 2 - 1, ((y + 0.5) / rows) * 2 - 1);
      }
      m[y * cols + x] = inside ? 1 : 0;
    }
  }
  return m;
}

// Доля клеток внутри фигуры (для расчёта размера сетки), с кэшем
const fillCache = new Map();
export function shapeFill(s) {
  if (!fillCache.has(s.id)) {
    const a = shapeAspect(s);
    const cols = Math.max(8, Math.round(48 * Math.sqrt(a)));
    const rows = Math.max(8, Math.round(48 / Math.sqrt(a)));
    const m = shapeMask(s, cols, rows);
    fillCache.set(s.id, m.reduce((t, v) => t + v, 0) / m.length);
  }
  return fillCache.get(s.id);
}
